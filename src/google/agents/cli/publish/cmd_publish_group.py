"""agents-cli publish command group."""

import click

from google.agents.cli._click import LazyGroup

_REGISTER_GEMINI = "google.agents.cli.publish.cmd_publish:register_gemini"
_REGISTER_GEMINI_SHORT_HELP = "Register a deployed agent with Gemini."


@click.group("publish", cls=LazyGroup)
def publish_group():
    """Publish agents to various targets.

    \b
    Subcommands:
      gemini  Register a deployed agent with Gemini
    """


publish_group.add_lazy_command("gemini", _REGISTER_GEMINI, _REGISTER_GEMINI_SHORT_HELP)
# Name before the Gemini rebrand. Projects generated by earlier versions call it
# from their Makefile, so it keeps working, just out of --help.
publish_group.add_lazy_command(
    "gemini-enterprise", _REGISTER_GEMINI, _REGISTER_GEMINI_SHORT_HELP, hidden=True
)
